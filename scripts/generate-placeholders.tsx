import { mkdirSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { PackageIcon, ScanSearchIcon, type LucideIcon } from "lucide-react"
import { renderToStaticMarkup } from "react-dom/server"

import { categoryIcons } from "@/components/catalog/category-icons"
import { PLACEHOLDER_VIEWS } from "@/lib/placeholders"

// pnpm images:placeholders: writes the placeholder product images to
// public/images/placeholders/ (docs/specs/006-product-images). The output is
// committed; re-run only to change the artwork.

// A Record type makes a missing view a type error; the category icons are
// shared with the home page's category tiles
const viewIcons: Record<keyof typeof PLACEHOLDER_VIEWS, LucideIcon> = {
  box: PackageIcon,
  detail: ScanSearchIcon,
}

// 240 × 240, icon 40% wide and centred, transparent background: the
// component's bg-muted box supplies the background, so it follows the theme.
// An SVG shown through <img> can't read CSS variables, so the icon uses a
// fixed mid-gray that reads on both the light and dark muted tokens.
const SIZE = 240
const ICON = 96
const GRAY = "#808080"

function render(Icon: LucideIcon): string {
  const offset = (SIZE - ICON) / 2
  const svg = renderToStaticMarkup(
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={`0 0 ${SIZE} ${SIZE}`}
      width={SIZE}
      height={SIZE}
    >
      <Icon
        x={offset}
        y={offset}
        width={ICON}
        height={ICON}
        color={GRAY}
        strokeWidth={2}
      />
    </svg>
  )
  return `<!-- Generated by scripts/generate-placeholders.tsx. Icon: Lucide (ISC License) -->\n${svg}\n`
}

const outDir = fileURLToPath(
  new URL("../public/images/placeholders/", import.meta.url)
)
mkdirSync(outDir, { recursive: true })

const icons = { ...categoryIcons, ...viewIcons }
for (const [name, Icon] of Object.entries(icons)) {
  writeFileSync(`${outDir}${name}.svg`, render(Icon))
}
console.log(`Wrote ${Object.keys(icons).length} placeholders to ${outDir}`)
